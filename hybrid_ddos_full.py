K1 = 2.0                # Stage 1 sensitivity (z-score) - low on purpose: Stage 1 is a high-recall pre-filter
K2 = 3.0                # Stage 2 sensitivity (lambda_t = mu -/+ k * sigma_t)
RECAL_EVERY = 60        # feedback loop: recalibrate Stage 1 every N windows
EWMA_ALPHA = 0.3

FLOW_FEATURES = [
    "Protocol", "Flow Duration", "Total Fwd Packets", "Total Backward Packets",
    "Total Length of Fwd Packets", "Total Length of Bwd Packets", "Flow Bytes/s",
    "Flow Packets/s", "Flow IAT Mean", "Flow IAT Std", "SYN Flag Count",
    "ACK Flag Count", "PSH Flag Count", "Packet Length Mean", "Init_Win_bytes_forward",
]

# %% STEP 1 - load, clean, window, chronological split
df = pd.read_csv(DATA, parse_dates=["Timestamp"]).sort_values("Timestamp").reset_index(drop=True)
df["y"] = (df["Label"] != "BENIGN").astype(int)
df["win"] = ((df["Timestamp"] - df["Timestamp"].min()).dt.total_seconds() // WINDOW_SEC).astype(int)
df["ts"] = (df["Timestamp"] - df["Timestamp"].min()).dt.total_seconds()

# inf -> NaN (CICIDS has inf in rate columns)
df[FLOW_FEATURES] = df[FLOW_FEATURES].replace([np.inf, -np.inf], np.nan)

# Chronological split by window id (NOT random: random flow split leaks neighbouring flows)
n_win = df["win"].max() + 1
TRAIN_END = int(n_win * 0.55)   # first 55% of time = train; rest = held-out test (includes an unseen attack type)
df["split"] = np.where(df["win"] < TRAIN_END, "train", "test")
print(df.groupby("split").agg(flows=("y", "size"), attack_flows=("y", "sum"),
                              windows=("win", "nunique")))

# Fill NaN with TRAIN medians, then log-compress and min-max scale (fit on benign train only)
train_med = df.loc[df.split == "train", FLOW_FEATURES].median()
df[FLOW_FEATURES] = df[FLOW_FEATURES].fillna(train_med)
X_raw = np.sign(df[FLOW_FEATURES].values) * np.log1p(np.abs(df[FLOW_FEATURES].values))
scaler = MinMaxScaler().fit(X_raw[((df.split == "train") & (df.y == 0)).values])
X = np.clip(scaler.transform(X_raw), -1, 2)

tr, te = [(df.split == s).values for s in ("train", "test")]
y = df["y"].values

# %% STEP 2 - Stage 1 features: Hurst exponent + correlation per window
def hurst_rs(x, min_chunk=4):
    """Rescaled-range Hurst exponent of a 1-D series."""
    x = np.asarray(x, float)
    n = len(x)
    if n < 8 or np.std(x) == 0:
        return 0.5
    sizes = np.unique(np.floor(np.logspace(np.log10(min_chunk), np.log10(n // 2), 6)).astype(int))
    used, rs = [], []
    for s in sizes:
        k = n // s
        if k < 1:
            continue
        ch = x[: k * s].reshape(k, s)
        dev = np.cumsum(ch - ch.mean(1, keepdims=True), axis=1)
        R, S = dev.max(1) - dev.min(1), ch.std(1)
        ok = S > 0
        if ok.any():
            used.append(s)
            rs.append(np.mean(R[ok] / S[ok]))
    if len(used) < 2:
        return 0.5
    return float(np.clip(np.polyfit(np.log(used), np.log(rs), 1)[0], 0, 1))

def safe_corr(a, b):
    if len(a) < 3 or np.std(a) == 0 or np.std(b) == 0:
        return 0.0
    return float(np.corrcoef(a, b)[0, 1])

CORR_PAIRS = [("Total Fwd Packets", "Total Length of Fwd Packets"),
              ("Flow Duration", "Flow IAT Mean"),
              ("Flow Packets/s", "Flow Bytes/s")]

def stage1_features(g):
    iat = np.diff(np.sort(g["ts"].values))
    corr = np.mean([abs(safe_corr(g[a].values, g[b].values)) for a, b in CORR_PAIRS])
    return pd.Series({"hurst": hurst_rs(iat), "corr": corr, "log_count": np.log1p(len(g))})

# %% STEP 3 - Stage 2 features: Shannon entropy per window
def norm_entropy(s):
    if len(s) < 2:
        return 0.0
    p = s.value_counts(normalize=True).values
    return float(-(p * np.log2(p)).sum() / np.log2(len(s)))

def stage2_features(g):
    return pd.Series({"H_src": norm_entropy(g["Source IP"]),
                      "H_port": norm_entropy(g["Destination Port"])})

t0 = time.perf_counter()
W1 = df.groupby("win").apply(stage1_features)
t_s1 = (time.perf_counter() - t0) / len(W1)
t0 = time.perf_counter()
W2 = df.groupby("win").apply(stage2_features)
t_s2_feat = (time.perf_counter() - t0) / len(W2)

W = W1.join(W2)
W["y"] = df.groupby("win")["y"].max()                       # window is attack if any attack flow
W["split"] = df.groupby("win")["split"].first()
W["attack_type"] = df[df.y == 1].groupby("win")["Attack Type"].agg(lambda s: s.mode()[0])
W["attack_type"] = W["attack_type"].fillna("BENIGN")
print(W.groupby("y")[["hurst", "corr", "log_count", "H_src", "H_port"]].mean().round(3))

# %% STEP 4 - Stage 2: GARCH(1,1) on entropy series -> dynamic threshold lambda_t
def garch_sigma(series, train_mask, benign_mask):
    """Fit GARCH(1,1) on benign TRAIN entropy, then run the variance recursion
    sigma2_t = omega + alpha*eps_{t-1}^2 + beta*sigma2_{t-1} over the whole series."""
    fit_data = series[train_mask & benign_mask] * 100
    res = arch_model(fit_data.values, mean="Constant", vol="GARCH", p=1, q=1).fit(disp="off")
    mu = res.params["mu"] / 100
    omega, alpha, beta = res.params["omega"] / 1e4, res.params["alpha[1]"], res.params["beta[1]"]
    x = series.values
    sig2 = np.empty(len(x))
    sig2[0] = np.var(fit_data.values / 100)
    for t in range(1, len(x)):
        eps = x[t - 1] - mu
        sig2[t] = omega + alpha * eps ** 2 + beta * sig2[t - 1]
    return mu, np.sqrt(sig2)

is_train = (W.split == "train").values
is_benign = (W.y == 0).values
t0 = time.perf_counter()
mu_src, sig_src = garch_sigma(W["H_src"], is_train, is_benign)
mu_port, sig_port = garch_sigma(W["H_port"], is_train, is_benign)
W["lam_src"] = mu_src - K2 * sig_src      # source-IP entropy DROPS under DDoS (few bots)
W["lam_port_hi"] = mu_port + K2 * sig_port  # dest-port entropy shifts the other way -> two-sided band
W["lam_port_lo"] = mu_port - K2 * sig_port
W["s2_flag"] = ((W.H_src < W.lam_src) | (W.H_port > W.lam_port_hi)
                | (W.H_port < W.lam_port_lo)).astype(int)
t_s2 = t_s2_feat + (time.perf_counter() - t0) / len(W)

# %% STEP 5 - Stage 3: autoencoder (benign only) + Random Forest on [features + recon error]
ae_backend = "keras"
try:
    import tensorflow as tf
    tf.random.set_seed(42)
    d = X.shape[1]
    inp = tf.keras.Input(shape=(d,))
    h = tf.keras.layers.Dense(10, activation="relu")(inp)
    z = tf.keras.layers.Dense(5, activation="relu")(h)
    h = tf.keras.layers.Dense(10, activation="relu")(z)
    out = tf.keras.layers.Dense(d, activation="linear")(h)
    ae = tf.keras.Model(inp, out)
    ae.compile(optimizer="adam", loss="mse")
    benign_train = X[tr & (y == 0)]
    ae.fit(benign_train, benign_train, epochs=25, batch_size=256, validation_split=0.1,
           verbose=0)
    recon = lambda A: ae.predict(A, verbose=0)
except ImportError:                      # fallback so the script still runs without TensorFlow
    from sklearn.neural_network import MLPRegressor
    ae_backend = "sklearn-MLP"
    ae = MLPRegressor(hidden_layer_sizes=(10, 5, 10), max_iter=200, random_state=42)
    ae.fit(X[tr & (y == 0)], X[tr & (y == 0)])
    recon = ae.predict
print("Autoencoder backend:", ae_backend)

err = np.mean((X - recon(X)) ** 2, axis=1)
df["ae_err"] = err
ae_thr = np.percentile(err[tr & (y == 0)], 95)              # AE-only baseline threshold

X_hyb = np.column_stack([X, err])
rf = RandomForestClassifier(n_estimators=150, max_depth=12, class_weight="balanced",
                            n_jobs=-1, random_state=42).fit(X_hyb[tr], y[tr])
rf_only = RandomForestClassifier(n_estimators=150, max_depth=12, class_weight="balanced",
                                 n_jobs=-1, random_state=42).fit(X[tr], y[tr])

t0 = time.perf_counter()
p_hyb = rf.predict_proba(X_hyb)[:, 1]
t_s3 = (time.perf_counter() - t0) / df["win"].nunique()
df["p_hyb"] = p_hyb
df["rf_pred"] = (p_hyb >= 0.5).astype(int)

# %% STEP 6 - Cascade with feedback loop (Stage 3 verdicts recalibrate Stage 1)
S1_COLS = ["hurst", "corr", "log_count"]
base = W.loc[is_train & is_benign, S1_COLS]
BASE_MU, BASE_SD = base.mean().values, base.std().replace(0, 1e-6).values

def run_cascade(adaptive):
    mu, sd = BASE_MU.copy(), BASE_SD.copy()
    buf, rows = [], []
    for w in W.index[(W.split == "test").values]:
        f = W.loc[w, S1_COLS].values.astype(float)
        s1 = int(np.any(np.abs((f - mu) / sd) > K1))
        s2_all = int(W.at[w, "s2_flag"])               # entropy is cheap, so it is always available
        s2 = s2_all if s1 else 0
        flows = df.index[df.win == w]
        if s1 and s2:                                   # Stage 3 only on twice-flagged windows
            fl_pred = df.loc[flows, "rf_pred"].values
            verdict = int(fl_pred.mean() >= 0.5)
        else:
            fl_pred, verdict = np.zeros(len(flows), int), 0
        rows.append((w, s1, s2, verdict, flows, fl_pred))
        # Feedback: only windows that Stage 2 (independent evidence) AND the final verdict call benign
        # recalibrate Stage 1. Using "not flagged by Stage 1" alone would let missed attacks poison it.
        if adaptive and verdict == 0 and s2_all == 0:
            buf.append(f)
        if adaptive and len(rows) % RECAL_EVERY == 0 and len(buf) >= 10:
            b = np.array(buf)
            mu = (1 - EWMA_ALPHA) * mu + EWMA_ALPHA * b.mean(0)
            sd = (1 - EWMA_ALPHA) * sd + EWMA_ALPHA * np.maximum(b.std(0), 1e-6)
            buf = []
    return rows

def collect(rows):
    win = pd.DataFrame([(w, a, b, c) for w, a, b, c, _, _ in rows],
                       columns=["win", "s1", "s2", "verdict"]).set_index("win")
    idx = np.concatenate([r[4] for r in rows])
    pred = np.concatenate([r[5] for r in rows])
    return win, pd.Series(pred, index=idx)

rows_static, rows_adapt = run_cascade(False), run_cascade(True)
win_static, flow_static = collect(rows_static)
win_adapt, flow_adapt = collect(rows_adapt)

# %% STEP 7 - Evaluation: metrics, baselines, plots
def metrics(y_true, y_pred, name):
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {"Model": name, "Accuracy": accuracy_score(y_true, y_pred),
            "Precision": precision_score(y_true, y_pred, zero_division=0),
            "Recall": recall_score(y_true, y_pred, zero_division=0),
            "F1": f1_score(y_true, y_pred, zero_division=0),
            "FPR": fp / max(fp + tn, 1)}

yt = y[te]
test_idx = df.index[te]
pred_hybrid = flow_adapt.reindex(test_idx).values
pred_hybrid_static = flow_static.reindex(test_idx).values
