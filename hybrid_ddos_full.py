# %% STEP 8 - Concept-drift test: does the feedback loop keep Stage 1 calibrated when traffic changes?
# Scenario: legitimate traffic volume grows steadily during the test period (flash crowd / business growth).
# Attack and benign windows both grow. Only the Stage 1 volume feature is shifted; flows, entropy and the
# trained models are untouched, so this is a window-level simulation, not new traffic.

def drift_experiment(final_factor, onset_frac=0.25):
    global W
    W_orig = W
    Wd = W_orig.copy()
    tw_idx = Wd.index[(Wd.split == "test").values]
    n = len(tw_idx)
    onset = int(n * onset_frac)
    ramp = np.clip((np.arange(n) - onset) / max(n - onset, 1), 0, 1)      # 0 -> 1 over the test period
    Wd.loc[tw_idx, "log_count"] = Wd.loc[tw_idx, "log_count"] + np.log(final_factor) * ramp
    W = Wd
    try:
        out = {}
        for name, adaptive in (("static", False), ("adaptive", True)):
            rows = run_cascade(adaptive)
            win, flow = collect(rows)
            pred = flow.reindex(test_idx).values
            m = metrics(yt, pred, name)
            tw = W[W.split == "test"]
            out[name] = {
                "Stage1 window recall": win.s1[tw.y == 1].mean(),
                "Stage1 window FPR": win.s1[tw.y == 0].mean(),
                "% flows reaching Stage 3": 100 * df.loc[te, "win"].map(win.s1 & win.s2).fillna(0).mean(),
                "Flow Recall": m["Recall"], "Flow FPR": m["FPR"], "Flow F1": m["F1"]}
        return pd.DataFrame(out).T
    finally:
        W = W_orig

drift_results = []
for factor in (1.0, 1.5, 2.0, 3.0):
    r = drift_experiment(factor)
    r.insert(0, "Final volume x", factor)
    drift_results.append(r)
drift_table = pd.concat(drift_results).round(4)
